-- Table to store temporary OTPs for Fast2SMS/Local Gateway verification
create table public.otp_requests (
  id uuid default gen_random_uuid() primary key,
  phone text not null, -- The Indian +91 number
  otp text not null, -- A 6 digit code generated by the Python backend
  attempts int default 0, -- Track failed attempts to prevent brute-forcing
  expires_at timestamp with time zone not null, -- OTPs should expire in 10 minutes
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Index phone numbers for fast verifications
create index idx_otp_requests_phone on public.otp_requests (phone);

-- Secure RLS: Only the Backend Python API (Service Role) can read/write this table
-- Citizens NEVER interact with this table directly via the client to prevent scraping.
alter table public.otp_requests enable row level security;

create policy "Allow service role full access to otps" 
on public.otp_requests for all 
using (true);
